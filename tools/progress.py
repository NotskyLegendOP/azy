ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "progress.json"
MD = ROOT / "docs" / "PROGRESS.md"
HTML = ROOT / "docs" / "progress.html"

# done is worth everything, partial half, todo/blocked nothing. "impossible" rows
# are excluded from the arithmetic (they are permanent, not pending) but are still
# rendered, so the board never quietly drops a requirement.
CREDIT = {"done": 1.0, "partial": 0.5, "impossible": None}
STATUS_LABEL = {
    "done": "done",
    "partial": "in progress",
    "todo": "to do",
    "blocked": "waiting on a decision",
    "impossible": "not possible",
    "user": "needs your machine",
}
CLASS_LABEL = {
    "A": "native, shipped",
    "B": "native, planned",
    "C": "closest possible",
    "D": "not attempted",
}


def phase_progress(phase: dict) -> tuple[float, int, int]:
    """Weighted completion of one phase: (fraction, weight counted, items counted)."""
    total = 0.0
    earned = 0.0
    counted = 0
    for item in phase["items"]:
        credit = CREDIT.get(item["status"], 0.0)
        if credit is None:
            continue
        weight = float(item.get("weight", 1))
        total += weight
        earned += weight * credit
        counted += 1
    if total == 0:
        return 1.0, 0, counted
    return earned / total, int(total), counted


def bar(fraction: float, width: int = 26, filled: str = "#", empty: str = ".") -> str:
    done = int(round(fraction * width))
    return filled * done + empty * (width - done)


def markdown(data: dict, computed: dict, stamp: str) -> str:
    out: list[str] = []
    out.append("# Azy Skin — implementation progress\n")
    out.append(f"*Generated from `docs/progress.json` by `tools/progress.py` on {stamp}. "
               "Do not edit this file by hand.*\n")
    out.append("Against: the Complete Implementation Specification (50 sections). "
               "Class A = native and shipped, B = native and planned, "
               "C = the closest possible treatment (the element itself is out of reach), "
               "D = needs injection and is not attempted. "
               "See [`FEASIBILITY.md`](FEASIBILITY.md) for why each row lands where it does.\n")

    overall = computed["overall"]
    out.append("```")
    out.append(f"overall  [{bar(overall, 32)}] {overall * 100:5.1f}%   "
               f"remaining ≈ {computed['eta_total']}")
    out.append("")
    for phase in computed["phases"]:
        out.append(f"{phase['id']:<3} {phase['title']:<28} [{bar(phase['fraction'], 24)}] "
                   f"{phase['fraction'] * 100:5.1f}%   {phase['eta']}")
    out.append("```\n")

    out.append("## Phases\n")
    for phase in computed["phases"]:
        out.append(f"### {phase['id']} — {phase['title']} · {phase['fraction'] * 100:.0f}%\n")
        out.append(f"*{phase['spec']}* — **{phase['eta']}**")
        if phase.get("next"):
            out.append(f"\nNext: {phase['next']}" if phase["fraction"] < 1 else "")
        out.append("")
        out.append("| Item | Class | Status | Notes |")
        out.append("|---|---|---|---|")
        for item in phase["items"]:
            note = item.get("note", "")
            if item["status"] == "blocked":
                note = "WAITING ON A DECISION" + (f" — {note}" if note else "")
            out.append(f"| {item['name']} | {item['class']} — {CLASS_LABEL[item['class']]} | "
                       f"{STATUS_LABEL.get(item['status'], item['status'])} | {note} |")
        out.append("")

    out.append("## Requirements that will not be built as written\n")
    out.append("Each of these is a permanent decision, not a backlog item: the technique it "
               "would need is one this project rules out (injection, hooking, patching, or "
               "constant screen capture). The closest possible treatment is named instead.\n")
    out.append("| Specification | Why it cannot be done, and what is done instead |")
    out.append("|---|---|")
    for row in data["out_of_scope"]:
        out.append(f"| {row['spec']} | {row['why']} |")
    out.append("")

    out.append("## Specification coverage at a glance\n")
    out.append("| Specification | Phase | Class | Status |")
    out.append("|---|---|---|---|")
    for row in data["spec_map"]:
        out.append(f"| {row['section']} | {row['phase']} | {row['class']} | "
                   f"{STATUS_LABEL.get(row['status'], row['status'])} |")
    out.append("")

    out.append("## Acceptance test (§45)\n")
    out.append("| Area | Row | Status | Note |")
    out.append("|---|---|---|---|")
    for row in data["acceptance"]:
        out.append(f"| {row['area']} | {row['row']} | {STATUS_LABEL.get(row['status'], row['status'])} | "
                   f"{row.get('note', '')} |")
    out.append("")
    out.append(f"Packaging and distribution: **{data['packaging']['status']}** — {data['packaging']['note']}\n")
    out.append("---\n")
    out.append("Regenerate with `python3 tools/progress.py`; view it in a browser with "
               "`python3 tools/progress.py --serve`.\n")
    return "\n".join(out)


