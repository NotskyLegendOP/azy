VALID_STATUS = {"done", "partial", "todo", "blocked", "impossible", "user"}
VALID_CLASS = {"A", "B", "C", "D"}


def validate(data: dict) -> list[str]:
    """Cheap guard against a typo silently counting as zero progress."""
    problems: list[str] = []
    for phase in data["phases"]:
        for item in phase["items"]:
            if item["status"] not in VALID_STATUS:
                problems.append(f"{phase['id']}: unknown status {item['status']!r} ({item['name']})")
            if item["class"] not in VALID_CLASS:
                problems.append(f"{phase['id']}: unknown class {item['class']!r} ({item['name']})")
    for row in data["spec_map"]:
        for cls in row["class"].split("/"):
            if cls not in VALID_CLASS:
                problems.append(f"spec_map: unknown class {cls!r} ({row['section']})")
        if row["status"] not in VALID_STATUS:
            problems.append(f"spec_map: unknown status {row['status']!r} ({row['section']})")
    for row in data["acceptance"]:
        if row["status"] not in VALID_STATUS:
            problems.append(f"acceptance: unknown status {row['status']!r} ({row['row']})")
    return problems


def normalize(text: str) -> str:
    """The timestamp is the only volatile field, so it is ignored when checking
    that the generated files are up to date with the data."""
    return re.sub(r"\d{4}-\d\d-\d\d \d\d:\d\d UTC", "<stamp>", text)


def compute(data: dict) -> dict:
    phases = []
    for phase in data["phases"]:
        fraction, weight, counted = phase_progress(phase)
        phases.append({**phase, "fraction": fraction, "weight": weight, "counted": counted})

    total = sum(p["weight"] for p in phases)
    earned = sum(p["weight"] * p["fraction"] for p in phases)
    overall = earned / total if total else 0.0

    # A session is one exchange of this kind: implement, build, verify, hand back.
    # The only unknown is how long testing on the user's machine takes.
    sessions = 0.0
    for phase in phases:
        if phase["fraction"] >= 0.999:
            continue
        numbers = [float(x) for x in re.findall(r"\d+(?:\.\d+)?", phase.get("eta", ""))]
        if numbers:
            # A range ("2-3 sessions") is counted at its upper bound: an estimate
            # that turns out optimistic is worse than one that turns out slow.
            sessions += max(numbers)
    eta_total = f"{sessions:.0f} work sessions" if sessions else "nothing scheduled"
    return {"phases": phases, "overall": overall, "eta_total": eta_total}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--serve", action="store_true", help="serve docs/progress.html after writing it")
    parser.add_argument("--check", action="store_true",
                        help="verify the generated files match the data; write nothing")
    parser.add_argument("--port", type=int, default=8111)
    args = parser.parse_args()

    data = json.loads(DATA.read_text(encoding="utf-8"))
    problems = validate(data)
    if problems:
        for problem in problems:
            print(f"progress data: {problem}", file=sys.stderr)
        return 1

    computed = compute(data)
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    rendered = {
        MD: markdown(data, computed, stamp),
        HTML: html_document(data, computed, stamp),
    }

    if args.check:
        for path, text in rendered.items():
            if not path.exists():
                print(f"missing: {path.relative_to(ROOT)} (run tools/progress.py)", file=sys.stderr)
                return 1
            if normalize(path.read_text(encoding="utf-8")) != normalize(text):
                print(f"out of date: {path.relative_to(ROOT)} (run tools/progress.py)",
                      file=sys.stderr)
                return 1
        print(f"progress board: in sync at {computed['overall'] * 100:.1f}%")
        return 0

    for path, text in rendered.items():
        path.write_text(text, encoding="utf-8")

    print(f"overall {computed['overall'] * 100:.1f}% (remaining ≈ {computed['eta_total']})")
    for phase in computed["phases"]:
        print(f"  {phase['id']} {phase['title']:<28} {phase['fraction'] * 100:5.1f}%  {phase['eta']}")
    print("wrote docs/PROGRESS.md and docs/progress.html")

    if args.serve:
        serve(args.port)
    return 0


def serve(port: int) -> None:  # pragma: no cover - interactive
    """Serves the board at / (and nothing else). Binds 0.0.0.0, not loopback, so a
    preview proxy in front of the sandbox can reach it."""
    import http.server
    import socketserver

    documents = ROOT / "docs"

    class Handler(http.server.SimpleHTTPRequestHandler):
        def __init__(self, *a, **k):
            super().__init__(*a, directory=str(documents), **k)

        def do_GET(self):  # noqa: N802 - the name is fixed by the base class
            if self.path in ("/", "/index.html"):
                self.path = "/progress.html"
            return super().do_GET()

        def log_message(self, *a):  # quiet: this is a viewer, not a server
            return

    socketserver.ThreadingTCPServer.allow_reuse_address = True
    with socketserver.ThreadingTCPServer(("0.0.0.0", port), Handler) as httpd:
        print(f"progress board: http://localhost:{port}/progress.html")
        httpd.serve_forever()


if __name__ == "__main__":
    sys.exit(main())
