#!/usr/bin/env python3
"""Renders the progress board from docs/progress.json.

    python3 tools/progress.py            # writes docs/PROGRESS.md + docs/progress.html
    python3 tools/progress.py --serve    # ... and serves it on http://localhost:8111/

The JSON is the single source of truth: it is the only file edited by hand, and
the two generated files are what the user reads (one in the repository, one in a
browser). Nothing here talks to the network or to Premiere.
"""

from __future__ import annotations

